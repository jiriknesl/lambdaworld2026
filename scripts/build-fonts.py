"""Embed project fonts as WOFF data URLs. Build dependency: fontTools.
The resulting CSS needs no installed fonts or font-server connection at runtime.
"""
from pathlib import Path
from io import BytesIO
from base64 import b64encode
import json
from fontTools.ttLib import TTFont
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

ROOT = Path(__file__).resolve().parent.parent
families = [("DejaVuSans.ttf", "Rescue Sans", "100 500"),
            ("DejaVuSans-Bold.ttf", "Rescue Sans", "600 900"),
            ("DejaVuSansMono.ttf", "Rescue Mono", "100 900")]


def outline(polygons):
    pen = TTGlyphPen(None)
    for points in polygons:
        pen.moveTo(points[0])
        for point in points[1:]:
            pen.lineTo(point)
        pen.closePath()
    return pen.glyph()


# Original, monochrome silhouettes. Unicode stays intact in runnable Clojure.
shapes = {
    "boat": [[(70,220),(930,220),(750,40),(240,40)],
             [(485,260),(530,260),(530,920),(485,920)],
             [(555,870),(555,310),(900,310)],[(450,720),(150,310),(450,310)]],
    "bird": [[(110,420),(260,500),(250,700),(380,620),(560,740),(750,740),
              (820,650),(960,580),(810,550),(770,360),(570,250),(380,270)],
             [(430,270),(470,270),(430,150),(540,150),(540,120),(370,120)],
             [(600,280),(640,280),(600,170),(690,170),(690,140),(550,140)]],
    "expand": [[(80,600),(80,920),(400,920),(400,860),(140,860),(140,600)],
               [(600,920),(920,920),(920,600),(860,600),(860,860),(600,860)],
               [(80,400),(140,400),(140,140),(400,140),(400,80),(80,80)],
               [(860,400),(920,400),(920,80),(600,80),(600,140),(860,140)]],
    "left": [[(600,850),(320,470),(600,90),(650,125),(395,470),(650,815)]],
    "right": [[(350,850),(650,470),(350,90),(300,125),(575,470),(300,815)]],
}
symbols = FontBuilder(1000, isTTF=True)
symbols.setupGlyphOrder([".notdef", "space", *shapes])
symbols.setupCharacterMap({32:"space",0x26f5:"boat",0x1f426:"bird",0x26f6:"expand",0x3008:"left",0x3009:"right"})
symbols.setupGlyf({".notdef":outline([]),"space":outline([]),**{name:outline(polys) for name,polys in shapes.items()}})
symbols.setupHorizontalMetrics({name:(1000,0) for name in symbols.font.getGlyphOrder()})
symbols.setupHorizontalHeader(ascent=950,descent=-150)
symbols.setupNameTable({"familyName":"Rescue Symbols","styleName":"Regular","uniqueFontIdentifier":"LambdaWorldRescueSymbols1","fullName":"Rescue Symbols","psName":"RescueSymbols"})
symbols.setupOS2(sTypoAscender=950,sTypoDescender=-150,usWinAscent=950,usWinDescent=150)
symbols.setupPost()

css = ["/* Generated by scripts/build-fonts.py. DejaVu license: /font-license.txt. */"]
coverage = set(symbols.font.getBestCmap())
for font, family, weight in [(TTFont(ROOT / "resources/fonts" / file),family,weight) for file,family,weight in families]+[(symbols.font,"Rescue Symbols","100 900")]:
    coverage.update(font.getBestCmap())
    font.flavor = "woff"
    out = BytesIO(); font.save(out)
    css.append('@font-face{font-family:"'+family+'";font-style:normal;font-weight:'+weight+';font-display:block;src:url(data:font/woff;base64,'+b64encode(out.getvalue()).decode()+') format("woff")}')
css.append('code,kbd,samp,pre{font-family:var(--mono)}button,input,textarea,select{font-family:inherit}')
css.append(':root{--sans:"Rescue Sans","Rescue Symbols";--mono:"Rescue Mono","Rescue Sans","Rescue Symbols"}')
(ROOT / "resources/public/fonts.css").write_text("\n".join(css)+"\n")
(ROOT / "resources/public/font-license.txt").write_text((ROOT / "resources/fonts/LICENSE.txt").read_text())
text = "".join(p.read_text() for directory in ["resources", "src"] for p in (ROOT/directory).rglob("*")
               if p.suffix in [".html",".clj",".edn",".js"])
missing = sorted({c for c in text if ord(c)>31 and ord(c) not in coverage})
if missing:
    raise SystemExit("Unbundled glyphs: "+repr(missing))
print("Embedded 3 DejaVu faces and original Unicode symbols; all presentation glyphs covered.")
